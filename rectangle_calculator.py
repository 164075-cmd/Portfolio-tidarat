# โค้ดเวอร์ชันใหม่ของฉัน
# พัฒนาจากต้นแบบ โดย: ธิดารัตน์ จันทร์เกษม

print("=== โปรแกรมคำนวณพื้นที่และเส้นรอบรูปสี่เหลี่ยม ===")
gwang = float(input("กรุณากรอกความกว้าง: "))
yao = float(input("กรุณากรอกความยาว: "))

area = gwang * yao
perimeter = 2 * (gwang + yao)

print("พื้นที่คือ:", area)
print("ความยาวเส้นรอบรูปคือ:", perimeter)
